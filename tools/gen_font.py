#!/usr/bin/env python3
"""Bakes printable ASCII (32..126) and a few extra characters (EXTRA: the copyright and
degree signs) from a TTF into src/gfx/font_data.h.

The atlas is a grid of fixed cells, one byte of coverage per texel: ASCII, then the
extra characters, then a solid cell (used to draw filled rectangles with the same
texture).

    python3 tools/gen_font.py /usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf

With --clock, bakes just the digits and ':' (the screensaver clock) large, each glyph
centred in its cell and the cells cropped to the glyphs' height, into
src/gfx/clock_font_data.h:

    python3 tools/gen_font.py --clock /usr/share/fonts/truetype/dejavu/DejaVuSans.ttf
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONT_PX = 20
COLS = 16
FIRST, LAST = 32, 126
EXTRA = [0xA9, 0xB0]  # (c) and degree sign
CLOCK_PX = 144
CLOCK_PAD = 3  # empty texels around the glyphs, so bilinear filtering stays inside a cell


def write_header(out: Path, ns: str, comment: str, consts: list, data: bytes) -> None:
    lines = [
        "#pragma once",
        comment,
        "// DejaVu fonts: Bitstream Vera license (free to embed and redistribute).",
        "#include <cstdint>",
        "",
        f"namespace pb::{ns} {{",
        *consts,
        "inline constexpr uint8_t kAtlas[] = {",
    ]
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join(str(b) for b in data[i : i + 24]) + ",")
    lines += ["};", f"}}  // namespace pb::{ns}", ""]
    out.write_text("\n".join(lines))


def clock(ttf: str) -> int:
    font = ImageFont.truetype(ttf, CLOCK_PX)
    chars = [chr(c) for c in range(ord("0"), ord(":") + 1)]
    boxes = [font.getbbox(c) for c in chars]
    top, bottom = min(b[1] for b in boxes), max(b[3] for b in boxes)
    cell_w = int(max(font.getlength(c) for c in chars)) + 2 * CLOCK_PAD
    cell_h = bottom - top + 2 * CLOCK_PAD
    count = len(chars) + 1  # + solid cell
    w, h = count * cell_w, cell_h
    img = Image.new("L", (w, h), 0)
    draw = ImageDraw.Draw(img)
    for i, c in enumerate(chars):
        x = i * cell_w + (cell_w - font.getlength(c)) / 2
        draw.text((x, CLOCK_PAD - top), c, font=font, fill=255)
    draw.rectangle([(count - 1) * cell_w, 0, w - 1, h - 1], fill=255)
    out = Path(__file__).resolve().parent.parent / "src" / "gfx" / "clock_font_data.h"
    write_header(
        out,
        "clock_font",
        f"// Generated by tools/gen_font.py --clock from {Path(ttf).name} at {CLOCK_PX}px. Do not edit.",
        [
            f"inline constexpr uint32_t kCellW = {cell_w}, kCellH = {cell_h}, kCols = {count};",
            f"inline constexpr uint32_t kAtlasW = {w}, kAtlasH = {h};",
            f"inline constexpr int kFirstChar = '0', kLastChar = ':', kSolidIndex = {count - 1};",
        ],
        img.tobytes(),
    )
    print(f"wrote {out} ({w}x{h}, cell {cell_w}x{cell_h})")
    return 0


def main() -> int:
    if len(sys.argv) > 1 and sys.argv[1] == "--clock":
        return clock(sys.argv[2] if len(sys.argv) > 2 else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf")
    ttf = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
    font = ImageFont.truetype(ttf, FONT_PX)
    ascent, descent = font.getmetrics()
    cell_w = int(round(font.getlength("M"))) + 1
    cell_h = ascent + descent + 1
    chars = list(range(FIRST, LAST + 1)) + EXTRA
    count = len(chars) + 1  # + solid cell
    rows = (count + COLS - 1) // COLS
    w, h = COLS * cell_w, rows * cell_h
    img = Image.new("L", (w, h), 0)
    draw = ImageDraw.Draw(img)
    for i, code in enumerate(chars):
        x, y = (i % COLS) * cell_w, (i // COLS) * cell_h
        draw.text((x, y), chr(code), font=font, fill=255)
    solid = count - 1
    sx, sy = (solid % COLS) * cell_w, (solid // COLS) * cell_h
    draw.rectangle([sx, sy, sx + cell_w - 1, sy + cell_h - 1], fill=255)

    out = Path(__file__).resolve().parent.parent / "src" / "gfx" / "font_data.h"
    write_header(
        out,
        "font",
        f"// Generated by tools/gen_font.py from {Path(ttf).name} at {FONT_PX}px. Do not edit.",
        [
            f"inline constexpr uint32_t kCellW = {cell_w}, kCellH = {cell_h}, kCols = {COLS};",
            f"inline constexpr uint32_t kAtlasW = {w}, kAtlasH = {h};",
            f"inline constexpr int kFirstChar = {FIRST}, kLastChar = {LAST}, kSolidIndex = {solid};",
            "inline constexpr char32_t kExtraChars[] = {" + ", ".join(hex(c) for c in EXTRA) + "};",
            f"inline constexpr int kExtraCount = {len(EXTRA)}, kExtraFirstIndex = {LAST - FIRST + 1};",
        ],
        img.tobytes(),
    )
    print(f"wrote {out} ({w}x{h}, cell {cell_w}x{cell_h})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
